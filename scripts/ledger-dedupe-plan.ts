// Plan the one-off merge of duplicate story-ledger rows written before the event log.
// Input: a JSON export with a `claims` array (story_claims rows). Judge verdicts come from
// eval/ledger/judge-cassette.json; with LEDGER_EVAL_JUDGE_URL/TOKEN set, missing pairs are
// asked of the worker and recorded. Output: a SQL file to review, then run in one transaction:
//   psql -1 -v ON_ERROR_STOP=1 -f ledger-dedupe.sql
// Usage: pnpm --filter @newscraft/newsroom-harness exec tsx ../../scripts/ledger-dedupe-plan.ts <export.json> <out.sql>
import { randomUUID } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { planDedupe, type ExportedClaimRow } from '../eval/ledger/dedupe';
import { Cassette } from '../eval/ledger/replay';

const [input, output] = process.argv.slice(2).map((path) => resolve(process.env.INIT_CWD || process.cwd(), path));
if (!input || !output) throw new Error('usage: ledger-dedupe-plan.ts <export.json> <out.sql>');
const rows = (JSON.parse(readFileSync(input, 'utf8')) as { claims: ExportedClaimRow[] }).claims;
const cassette = new Cassette(resolve(import.meta.dirname, '../eval/ledger/judge-cassette.json'));
const url = process.env.LEDGER_EVAL_JUDGE_URL;
const judge = url ? cassette.recording(url, process.env.LEDGER_EVAL_JUDGE_TOKEN || '') : cassette.judge;
const plan = await planDedupe(rows, judge, Date.now(), () => `dd-${randomUUID()}`);
if (url) cassette.save();
writeFileSync(output, ['-- Story ledger duplicate merge (generated by scripts/ledger-dedupe-plan.ts)', ...plan.statements, ''].join('\n'));
console.log(JSON.stringify({ rows: rows.length, merges: plan.merges.length, conflicts: plan.conflicts.length, unjudged: cassette.missing.length }));
for (const merge of plan.merges) console.log(`MERGE  ${merge.fromText}\n   ->  ${merge.intoText}`);
for (const conflict of plan.conflicts) console.log(`CONFLICT  ${conflict.aText}\n     vs   ${conflict.bText}`);
